  var STORAGE_KEY = "gis-lang";
  var lang = "en";

  function readStored() {
    try { return localStorage.getItem(STORAGE_KEY); } catch (e) { return null; }
  }
  function writeStored(v) {
    try { localStorage.setItem(STORAGE_KEY, v); } catch (e) { /* storage blocked: ignore */ }
  }

  function t(key) {
    return (DICT[lang] && DICT[lang][key]) || DICT.en[key] || key;
  }

  function applyDocumentLang() {
    var html = document.documentElement;
    html.lang = lang;
    html.dir = lang === "ur" ? "rtl" : "ltr";
  }

  // Fills translated text and accessible attributes from the current dictionary.
  function applyI18n(root) {
    (root || document).querySelectorAll("[data-i18n], [data-i18n-alt], [data-i18n-content], [data-i18n-aria-label], [data-i18n-aria-roledescription]").forEach(function (el) {
      if (el.hasAttribute("data-i18n")) el.textContent = t(el.getAttribute("data-i18n"));
      if (el.hasAttribute("data-i18n-alt")) el.setAttribute("alt", t(el.getAttribute("data-i18n-alt")));
      if (el.hasAttribute("data-i18n-content")) el.setAttribute("content", t(el.getAttribute("data-i18n-content")));
      if (el.hasAttribute("data-i18n-aria-label")) el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria-label")));
      if (el.hasAttribute("data-i18n-aria-roledescription")) el.setAttribute("aria-roledescription", t(el.getAttribute("data-i18n-aria-roledescription")));
    });
  }

  function setLang(next) {
    if (!DICT[next]) return;
    lang = next;
    writeStored(next);
    applyDocumentLang();
    document.dispatchEvent(new CustomEvent("gis:langchange", { detail: { lang: next } }));
  }

  function init() {
    var stored = readStored();
    var fromUrl = new URLSearchParams(window.location.search).get("lang");
    lang = DICT[fromUrl] ? fromUrl : (DICT[stored] ? stored : "en");
    applyDocumentLang();
  }

  window.GIS = window.GIS || {};
  window.GIS.i18n = {
    init: init, t: t, setLang: setLang, applyI18n: applyI18n,
    getLang: function () { return lang; }
  };
